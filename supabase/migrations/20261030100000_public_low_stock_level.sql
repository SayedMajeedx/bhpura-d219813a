-- A product page says a size is nearly gone at the store's own low-stock level.
--
-- The page wrote "only N left!" with a pulsing flame at five pieces or fewer, whatever the store had
-- set, and "N available" beside every other size: a visitor read the store's stock and a boutique
-- with one piece per size was "nearly gone" on every page. The store's level
-- (business_settings.low_stock_threshold, migration 20261012180000: 5 by default, 0 turns the
-- warning off) already decides "low" in the admin; the page now reads it too
-- (src/features/product-page/lib/stock-line.ts) and says nothing above it.
--
-- The public settings view (equal to 20261027160000's, the last to redefine it) gains the level at
-- its end. The level is a setting, not stock: it says nothing about what a store holds. Nothing is
-- written for any store.

