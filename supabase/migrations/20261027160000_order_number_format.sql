-- A store's own order numbers (the owner's decision of 2026-10-27): a prefix of up to six letters,
-- digits or dashes and a least number of digits, so order 1042 reads "PL-01042" instead of
-- "#1042" wherever an order number is shown (the admin, invoices, emails, the shopper's pages).
-- The number itself keeps counting as before (`next_invoice_number`); only how it is written
-- changes. Read with `orderNumberLabel` (src/lib/order-number.ts).

ALTER TABLE public.business_settings
  ADD COLUMN IF NOT EXISTS order_number_prefix text,
  ADD COLUMN IF NOT EXISTS order_number_digits smallint;

ALTER TABLE public.business_settings DROP CONSTRAINT IF EXISTS business_settings_order_number_prefix_shape;
ALTER TABLE public.business_settings ADD CONSTRAINT business_settings_order_number_prefix_shape
  CHECK (order_number_prefix IS NULL OR order_number_prefix ~ '^[A-Za-z0-9-]{1,6}$');
ALTER TABLE public.business_settings DROP CONSTRAINT IF EXISTS business_settings_order_number_digits_range;
ALTER TABLE public.business_settings ADD CONSTRAINT business_settings_order_number_digits_range
  CHECK (order_number_digits IS NULL OR order_number_digits BETWEEN 1 AND 8);

COMMENT ON COLUMN public.business_settings.order_number_prefix IS
  'Written before an order number ("PL-"); none: "#".';
COMMENT ON COLUMN public.business_settings.order_number_digits IS
  'The least digits an order number is written with (zeros in front); none: as it is.';

