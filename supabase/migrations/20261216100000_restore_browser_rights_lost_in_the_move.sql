-- and every policy came across unchanged, but the rights on functions and tables did not: the
-- restored objects took Supabase's defaults, which let every API caller (a visitor with the public
-- key: `anon`; any signed-in account: `authenticated`) execute every function and use every table.
-- The REVOKEs that our migrations had made were lost. What that opened, among others:
--   - get_integration_credential_secret and get_decrypted_instagram_token: any visitor could read a
--     store's saved keys (ad platforms' tokens, Instagram);
--   - apply_inventory_movement, the stock ledger: it lets a caller with no session through (the
