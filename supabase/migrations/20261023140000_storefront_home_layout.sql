-- How a store's home page sells: a shop's, or a menu's.
--
-- The storefront's home page was a shop's for everyone: a hero, rails of new arrivals and best
-- sellers, the whole catalogue to browse. A bakery's or a roastery's customer knows what they came
-- for and wants it in the basket fast, so such a store's home can be a menu (MenuHome): the store's
-- categories as tabs, each item a row with its price and one button (add, then a quantity; or
-- choose its weight or flavour), what the signed-in customer ordered before, and the basket at
-- the foot of the screen.
--
-- storefront_home_layout ('shop' or 'menu') is set in Settings > Home page; while a store has
-- chosen none (null, every store today) it is its vertical's (VERTICAL_DESIGN_PRESETS.homeLayout
-- in src/lib/brand-templates/design-presets.ts, read by storefrontHomeLayout): the menu for food
-- and coffee, the shop for everyone else. A store that sells only services keeps its own home
-- (ServicesHome), and a catalog store (no basket) keeps the shop's. Nothing is written for the
-- stores that exist.
--
-- Additive: the column, and the public settings view gains it at its end (the rest is the live
-- definition unchanged, as migration 20261023130000 left it). Guarded by
-- tests/menu-home-layout-migration.test.ts.

ALTER TABLE public.business_settings
  ADD COLUMN IF NOT EXISTS storefront_home_layout text
  CONSTRAINT business_settings_storefront_home_layout_check
  CHECK (storefront_home_layout IS NULL OR storefront_home_layout IN ('shop', 'menu'));

COMMENT ON COLUMN public.business_settings.storefront_home_layout IS
  'How the storefront''s home page sells (shop or menu); null: the store vertical''s (src/lib/brand-templates/design-presets.ts).';

